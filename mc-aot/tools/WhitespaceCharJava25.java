/** Generates exact Character.isWhitespace(char) ranges for JDK 25. */
public class WhitespaceCharJava25 {
  public static void main(String[] args) {
    if (Runtime.version().feature() != 25) throw new IllegalStateException("JDK 25 required");
    System.out.println("// Generated by tools/WhitespaceCharJava25.java with Java 25.");
    System.out.println("static WHITESPACE_CHAR_JAVA25: &[(u16,u16)] = &[");
    for(int i=0;i<=0xffff;) {
      if(!Character.isWhitespace((char)i)){i++;continue;}
      int start=i;while(i<0xffff && Character.isWhitespace((char)(i+1)))i++;
      System.out.printf("    (0x%04x,0x%04x),%n",start,i);i++;
    }
    System.out.println("]; ");
  }
}
