/** Generates the exact Character.toUpperCase(char) table from JDK 25. */
public class UppercaseCharJava25 {
  public static void main(String[] args) {
    if (Runtime.version().feature() != 25) throw new IllegalStateException("JDK 25 required");
    System.out.println("// Generated by tools/UppercaseCharJava25.java with Java 25.");
    System.out.println("static UPPER_CHAR_JAVA25: &[(u16,u16)] = &[");
    for (int i=0;i<=0xffff;i++) {
      char out=Character.toUpperCase((char)i);
      if (out!=i) System.out.printf("    (0x%04x,0x%04x),%n",i,(int)out);
    }
    System.out.println("]; ");
  }
}
